/** Deterministic Wire completion data only; no native owner or runtime admission. */
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { isDeepStrictEqual } from "node:util";
import { brotliCompressSync, constants } from "node:zlib";
import { CURRENT_SCHEMATIC_WIRE_COMPLETION_ROLES, CURRENT_SCHEMATIC_WIRE_COMPLETION_SOURCE } from "../server/src/current-schematic-wire-completion-source.review.ts";
import { unpackFixedRuntimeData } from "../server/src/fixed-runtime-data-storage.ts";
import type { PackedFixedRuntimeData } from "../server/src/fixed-runtime-data-storage.ts";

const sha256 = (bytes: Uint8Array): string => createHash("sha256").update(bytes).digest("hex");
function assertLosslessJson(value: unknown, ancestors = new Set<object>(), depth = 0): void {
  if (depth > 64) { throw new Error("FIXED_RUNTIME_DATA_REVIEW_DEPTH"); }
  if (value === null || typeof value === "string" || typeof value === "boolean") { return; }
  if (typeof value === "number" && Number.isFinite(value) && !Object.is(value, -0)) { return; }
  if (typeof value !== "object" || ancestors.has(value) || Object.getOwnPropertySymbols(value).length > 0 ||
      (!Array.isArray(value) && Object.getPrototypeOf(value) !== Object.prototype)) {
    throw new Error("FIXED_RUNTIME_DATA_REVIEW_NOT_JSON");
  }
  ancestors.add(value);
  const entries = Object.entries(Object.getOwnPropertyDescriptors(value));
  let arrayItems = 0;
  for (const [key, descriptor] of entries) {
    if (!(Array.isArray(value) && key === "length")) {
      if (descriptor.enumerable !== true || !Object.hasOwn(descriptor, "value")) { throw new Error("FIXED_RUNTIME_DATA_REVIEW_DESCRIPTOR"); }
      if (Array.isArray(value) && key !== String(arrayItems)) { throw new Error("FIXED_RUNTIME_DATA_REVIEW_ARRAY"); }
      if (Array.isArray(value)) { arrayItems += 1; }
      const child: unknown = descriptor.value;
      assertLosslessJson(child, ancestors, depth + 1);
    }
  }
  if (Array.isArray(value) && arrayItems !== value.length) { throw new Error("FIXED_RUNTIME_DATA_REVIEW_ARRAY_LENGTH"); }
  ancestors.delete(value);
}
export function packFixedRuntimeData(value: unknown): PackedFixedRuntimeData {
  assertLosslessJson(value);
  const raw = Buffer.from(JSON.stringify(value));
  if (raw.length === 0 || raw.length > 1_048_576) { throw new Error("FIXED_RUNTIME_DATA_REVIEW_BOUND"); }
  // oxlint-disable-next-line node/no-sync -- Deterministic bounded compression occurs only in this generator.
  const packed = brotliCompressSync(raw, { params: {
    [constants.BROTLI_PARAM_MODE]: constants.BROTLI_MODE_TEXT,
    [constants.BROTLI_PARAM_QUALITY]: 11, [constants.BROTLI_PARAM_SIZE_HINT]: raw.length,
  } });
  const result: PackedFixedRuntimeData = { encoding: "brotli-json.v1", rawBytes: raw.length, rawSha256: sha256(raw),
    packedBytes: packed.length, packedSha256: sha256(packed), base64: packed.toString("base64") };
  const restored = unpackFixedRuntimeData(result);
  if (!isDeepStrictEqual(restored, value) || JSON.stringify(restored) !== raw.toString("utf8")) {
    throw new Error("FIXED_RUNTIME_DATA_REVIEW_ROUND_TRIP");
  }
  return result;
}
export function generateCurrentSchematicWireCompletionData(): string {
 const data=[CURRENT_SCHEMATIC_WIRE_COMPLETION_SOURCE,CURRENT_SCHEMATIC_WIRE_COMPLETION_ROLES];
 const packed=packFixedRuntimeData(data);
 return `// Generated by scripts/generate-schematic-wire-completion-data.ts; edit the readable Wire review companion.
 // Inert fixed data; decoder bounds and both SHA-256 identities are mandatory.
 // oxlint-disable unicorn/numeric-separators-style -- Generated JSON metadata uses canonical integer literals.
 import type { PackedFixedRuntimeData } from "./fixed-runtime-data-storage.ts";

 export const PACKED_SCHEMATIC_WIRE_COMPLETION_DATA: PackedFixedRuntimeData = ${JSON.stringify(packed)};
`.replaceAll(/^ /gmu,"");
}
async function main():Promise<void>{
 const mode=process.argv[2];if(process.argv.length!==3||(mode!=="--check"&&mode!=="--write")){throw new Error("Usage: generate-schematic-wire-completion-data.ts --check|--write");}
 const output=generateCurrentSchematicWireCompletionData(),path=resolve(import.meta.dirname,"../server/src/current-schematic-wire-completion-data-packed.ts");
 if(mode==="--write"){await writeFile(path,output);}else if(await readFile(path,"utf8")!==output){throw new Error("WIRE_COMPLETION_DATA_STALE");}
 process.stdout.write(`Wire completion data ${mode} verified.\n`);
}
if(import.meta.main){
 // oxlint-disable-next-line node/no-top-level-await -- Fixed generator CLI; imports perform no filesystem operations.
 await main();
}
