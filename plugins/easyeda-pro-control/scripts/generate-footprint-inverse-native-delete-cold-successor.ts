/** Reproduce the isolated successor with its own fixed native purpose. */
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { generateWorkerStartupProtocol } from "./generate-worker-startup-protocol.ts";
import { CURRENT_NATIVE_BASELINE, assertCurrentNativeBaseline } from "./native-baseline-source.ts";
import { applyCurrentFootprintInverseNativeDeleteColdNativeFragment } from "../server/src/current-footprint-inverse-native-delete-cold-native-fragment.ts";
import { CURRENT_FOOTPRINT_INVERSE_NATIVE_DELETE_COLD_PROFILE as PROFILE } from "../server/src/current-footprint-inverse-native-delete-cold-profile.ts";
import { currentPcbDiagnosticCSharpReviewSource, currentPcbDiagnosticCSharpRuntimeCompilerInput, expandCurrentPcbDiagnosticCSharpReviewSource, packCurrentPcbDiagnosticCSharpReviewStorage } from "../server/src/current-pcb-diagnostic-csharp-review-storage.ts";
import { CURRENT_PCB_DIAGNOSTIC_HELPER_SOURCE_MAX_BYTES as MAXIMUM } from "../server/src/current-pcb-diagnostic-helper-source-profile.ts";

const helperPath = "scripts/footprint-inverse-native-delete-cold-successor.ps1";
const reviewPath = "scripts/footprint-inverse-native-delete-cold-successor.cs";
const identityPath = "server/src/current-footprint-inverse-native-delete-cold-successor-identity.ts";
const hash = (value: string): string => createHash("sha256").update(value).digest("hex");
const pin = (source: string): Readonly<{ bytes: number; sha256: string }> => Object.freeze({ bytes: Buffer.byteLength(source), sha256: hash(source) });

export function generateFootprintInverseNativeDeleteColdSuccessor(seed: string): Readonly<{ files: readonly Readonly<{ path: string; source: string }>[]; compiler: string }> {
  assertCurrentNativeBaseline(seed);
  const predecessor = generateWorkerStartupProtocol(seed);
  const predecessorPin = pin(predecessor);
  if (predecessorPin.bytes !== 1_589_072 || predecessorPin.sha256 !== "f52b8e12f4354d1179f097750aa177a288c3e15afbd4eb11f7af3c629fc4479c") {
    throw new Error("INVERSE_NATIVE_DELETE_COLD_PREDECESSOR");
  }
  const projected = applyCurrentFootprintInverseNativeDeleteColdNativeFragment(expandCurrentPcbDiagnosticCSharpReviewSource(predecessor));
  const helper = packCurrentPcbDiagnosticCSharpReviewStorage(projected);
  const review = currentPcbDiagnosticCSharpReviewSource(helper);
  const compiler = currentPcbDiagnosticCSharpRuntimeCompilerInput(helper);
  if (Buffer.byteLength(helper) > MAXIMUM || Buffer.byteLength(compiler) > MAXIMUM || expandCurrentPcbDiagnosticCSharpReviewSource(helper) !== projected) {
    throw new Error("INVERSE_NATIVE_DELETE_COLD_BUILD_BOUND");
  }
  const identity = {
    schema: "private.current-footprint-inverse-native-delete-cold-successor-identity.v1",
    layout: PROFILE.helperLayout,
    predecessor: predecessorPin,
    helper: { relativePath: helperPath, ...pin(helper) },
    review: { relativePath: reviewPath, ...pin(review) },
    compiler: pin(compiler),
  } as const;
  const text = `/** Generated readonly successor identity. */\n/* oxlint-disable unicorn/numeric-separators-style -- Exact generated byte pins preserve canonical JSON numeric spelling. */\nexport const CURRENT_FOOTPRINT_INVERSE_NATIVE_DELETE_COLD_SUCCESSOR_IDENTITY=Object.freeze({${Object.entries(identity).map(([key, value]) => `${key}:${typeof value==="string"?JSON.stringify(value):`Object.freeze(${JSON.stringify(value)} as const)`}`).join(",")}} as const);\n`;
  return Object.freeze({ files: Object.freeze([
    Object.freeze({ path: helperPath, source: helper }), Object.freeze({ path: reviewPath, source: review }),
    Object.freeze({ path: identityPath, source: text }),
  ]), compiler });
}

async function main(): Promise<void> {
  const mode = process.argv[2];
  if (process.argv.length !== 3 || mode !== "--write" && mode !== "--check") { throw new Error("INVERSE_NATIVE_DELETE_COLD_BUILD_ARGUMENT"); }
  const seed = await readFile(new URL(`../${CURRENT_NATIVE_BASELINE.relativePath}`, import.meta.url), "utf8");
  const { files, compiler } = generateFootprintInverseNativeDeleteColdSuccessor(seed);
  for (const file of files) {
    const url = new URL(`../${file.path}`, import.meta.url);
    if (mode === "--write") { await writeFile(url, file.source, { mode: 0o644 }); }
    else if (await readFile(url, "utf8") !== file.source) { throw new Error("INVERSE_NATIVE_DELETE_COLD_GENERATED_SOURCE_CHANGED"); }
  }
  process.stdout.write(`${JSON.stringify({ ok: true, compiled: false, files: files.map(file => { const info = pin(file.source); return { path: file.path, bytes: info.bytes, sha256: info.sha256 }; }), compiler: pin(compiler) })}\n`);
}

// oxlint-disable-next-line node/no-top-level-await -- Fixed build entrypoint performs no native execution.
if (import.meta.main) { await main(); }
