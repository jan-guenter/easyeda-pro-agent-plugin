import { createHash } from "node:crypto";
import { readFile, stat, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

import { inventoryApiDeclarations } from "../server/src/extension-api-declarations.ts";
import type { ApiDeclarationSnapshot } from "../server/src/extension-api-declarations.ts";

const sources = [
  { reference: "reviewed-installed", version: "0.2.53.aee2f57a", applicationVersion: "3.2.149.88089769",
    sourceUrl: "https://prodocs.easyeda.com/en/api/reference/pro-api.html",
    sourceSha256: "32a0d2f8b4bc3d7b2b93b33499d9d768b0c23c77f45843a65166cf4e8ad6dab1", license: "Installed declaration metadata; signatures only, no implementation", argument: 2 },
  { reference: "official-latest", version: "0.4.26", applicationVersion: null,
    sourceUrl: "https://cdn.jsdelivr.net/npm/@jlceda/pro-api-types@0.4.26/index.d.ts",
    sourceSha256: "7b2a0407ec516ea3f5021c8373d24cdced2a3946f990a4a524ec3ec394a1173f", license: "Apache-2.0; Copyright JLCEDA", argument: 3 },
] as const;

function codeLiteral(value: unknown): string {
  return JSON.stringify(value).split(/("(?:[^"\\]|\\.)*")/gu).map((part, index) => index % 2 === 0
    ? part.replaceAll(/\b\d{5,}\b/gu, (number) => number.replaceAll(/\B(?=(?:\d{3})+(?!\d))/gu, "_")) : part).join("");
}

async function generate(): Promise<void> {
if (process.argv.length !== 4) { throw new Error("Usage: generate-extension-api-catalog.ts REVIEWED_DECLARATIONS LATEST_DECLARATIONS"); }
const snapshots: ApiDeclarationSnapshot[] = [];
for (const source of sources) {
  const path = process.argv[source.argument];
  if (path === undefined || path === "") { throw new Error("Missing declaration path."); }
  const sourceStats = await stat(path);
  if (!sourceStats.isFile() || sourceStats.size > 2_097_152) { throw new Error("Declaration must be a bounded regular file."); }
  const bytes = await readFile(path);
  if (bytes.length > 2_097_152 || createHash("sha256").update(bytes).digest("hex") !== source.sourceSha256) { throw new Error(`Declaration does not match the separately reviewed ${source.reference} hash.`); }
  const { argument: _argument, ...metadata } = source;
  snapshots.push({ ...metadata, sourceBytes: bytes.length, retrievedAt: "2026-10-10", ...inventoryApiDeclarations(bytes.toString("utf8")) });
}
const serialized = snapshots.map((snapshot) => {
  const { namespaces, types, ...metadata } = snapshot;
  return `${codeLiteral(metadata).slice(0, -1)}, namespaces:[\n${namespaces.map((entry) => codeLiteral(entry)).join(",\n")}\n], types:${codeLiteral(types)}}`;
}).join(",\n");
const output = `// Generated by scripts/generate-extension-api-catalog.ts from separately hash-pinned declarations.\n// Documentation only; declaration presence never authorizes invocation or implies live validation.\nimport type { ApiDeclarationSnapshot } from "./extension-api-declarations.ts";\n\nexport const extensionApiSnapshots: readonly ApiDeclarationSnapshot[] = [\n${serialized}\n];\n`;
await writeFile(resolve(import.meta.dirname, "../server/src/extension-api-catalog-data.ts"), output);
}

// oxlint-disable-next-line node/no-top-level-await -- This generator is a CLI entrypoint, never an imported runtime module.
await generate();
