import { createHash } from "node:crypto";
import { readFile, stat, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { inventoryApiDeclarations } from "../server/src/extension-api-declarations.ts";
import type { ApiDeclarationSnapshot } from "../server/src/extension-api-declarations.ts";

const SOURCE_SHA256 = "0a6910f4108f3d09733a9de9176b20c41ccd2a87fc4e335f8d6d656eb054ba72";
const SOURCE_BYTES = 1_814_791;

function codeLiteral(value: unknown): string {
  return JSON.stringify(value).split(/("(?:[^"\\]|\\.)*")/gu).map((part, index) => index % 2 === 0
    ? part.replaceAll(/\b\d{5,}\b/gu, (number) => number.replaceAll(/\B(?=(?:\d{3})+(?!\d))/gu, "_")) : part).join("");
}

async function generate(): Promise<void> {
  const [mode, sourcePath] = process.argv.slice(2);
  if (process.argv.length !== 4 || (mode !== "--check" && mode !== "--write") || sourcePath === undefined || sourcePath === "") {
    throw new Error("Usage: generate-installed-209-api-catalog.ts --check|--write INSTALLED_209_DECLARATIONS");
  }
  const metadata = await stat(sourcePath);
  if (!metadata.isFile() || metadata.size !== SOURCE_BYTES) { throw new Error("Installed 209 declaration must have the reviewed regular-file size."); }
  const bytes = await readFile(sourcePath);
  if (bytes.length !== SOURCE_BYTES || createHash("sha256").update(bytes).digest("hex") !== SOURCE_SHA256) {
    throw new Error("Installed 209 declaration does not match its separately reviewed hash.");
  }
  const snapshot: ApiDeclarationSnapshot = {
    reference: "installed-209", version: "0.3.59.1ca9efb5", applicationVersion: "3.2.209.8a704eab",
    sourceUrl: "https://prodocs.easyeda.com/en/api/reference/pro-api.html", sourceSha256: SOURCE_SHA256,
    sourceBytes: bytes.length, retrievedAt: "2026-10-23", license: "Installed declaration metadata; signatures only, no implementation",
    ...inventoryApiDeclarations(bytes.toString("utf8")),
  };
  const { namespaces, types, ...provenance } = snapshot;
  const serialized = `${codeLiteral(provenance).slice(0, -1)}, namespaces:[\n${namespaces.map((entry) => codeLiteral(entry)).join(",\n")}\n], types:${codeLiteral(types)}}`;
  const output = `// Generated by scripts/generate-installed-209-api-catalog.ts from the exact separately pinned declaration.\n// Discovery only; installed declaration presence is not backend or execution support.\nimport type { ApiDeclarationSnapshot } from "./extension-api-declarations.ts";\n\nexport const installed209ApiSnapshot: ApiDeclarationSnapshot = ${serialized};\n`;
  const outputPath = resolve(import.meta.dirname, "../server/src/extension-api-installed-209-data.ts");
  if (mode === "--check") {
    if (await readFile(outputPath, "utf8") !== output) { throw new Error("Installed 209 declaration catalog is stale."); }
  } else { await writeFile(outputPath, output); }
  process.stdout.write(`Installed 209 declaration catalog ${mode === "--check" ? "verified" : "generated"}.\n`);
}

// oxlint-disable-next-line node/no-top-level-await -- This generator is a CLI entrypoint and cannot execute through a catalog query.
await generate();
