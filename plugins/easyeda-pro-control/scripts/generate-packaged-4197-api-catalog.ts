import { createHash } from "node:crypto";
import { constants } from "node:fs";
import { lstat, open, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { inventoryApiDeclarations } from "../server/src/extension-api-declarations.ts";
import type { ApiDeclarationSnapshot } from "../server/src/extension-api-declarations.ts";

const SOURCE_SHA256 = "773046ae11ae9291215226858c7dfc9f8121bbba5f0e7c71d29cd7aa53c81257";
const SOURCE_BYTES = 1_857_649;

function codeLiteral(value: unknown): string {
  return JSON.stringify(value).split(/("(?:[^"\\]|\\.)*")/gu).map((part, index) => index % 2 === 0
    ? part.replaceAll(/\b\d{5,}\b/gu, number => number.replaceAll(/\B(?=(?:\d{3})+(?!\d))/gu, "_")) : part).join("");
}

async function generate(): Promise<void> {
  const [mode, sourcePath] = process.argv.slice(2);
  if (process.argv.length !== 4 || (mode !== "--check" && mode !== "--write") || sourcePath === undefined || sourcePath === "") {
    throw new Error("Usage: generate-packaged-4197-api-catalog.ts --check|--write PACKAGED_4197_DECLARATIONS");
  }
  // oxlint-disable-next-line no-bitwise -- Combine kernel open flags to reject symlinks and avoid blocking on non-regular sources.
  const handle = await open(sourcePath, constants.O_RDONLY | constants.O_NOFOLLOW | constants.O_NONBLOCK);
  let bytes: Buffer;
  try {
    const before = await handle.stat({ bigint: true });
    if (!before.isFile() || before.nlink !== 1n || before.size !== BigInt(SOURCE_BYTES)) { throw new Error("Packaged declaration must have the reviewed regular-file identity and size."); }
    bytes = Buffer.alloc(SOURCE_BYTES + 1);
    let offset = 0;
    while (offset < bytes.length) {
      const result = await handle.read(bytes, offset, bytes.length - offset, offset);
      if (result.bytesRead === 0) { break; }
      offset += result.bytesRead;
    }
    const after = await handle.stat({ bigint: true }), named = await lstat(sourcePath, { bigint: true });
    if (offset !== SOURCE_BYTES || [after, named].some(value => !value.isFile() || value.nlink !== 1n ||
      value.dev !== before.dev || value.ino !== before.ino || value.size !== before.size || value.mtimeNs !== before.mtimeNs || value.ctimeNs !== before.ctimeNs)) {
      throw new Error("Packaged declaration changed while reading.");
    }
    bytes = bytes.subarray(0, SOURCE_BYTES);
    if (createHash("sha256").update(bytes).digest("hex") !== SOURCE_SHA256) { throw new Error("Packaged declaration does not match its separately reviewed hash."); }
  } finally { await handle.close(); }
  const snapshot: ApiDeclarationSnapshot = {
    reference: "packaged-4197", version: "0.3.69.f840f579", applicationVersion: "4.1.97.04b092ac",
    sourceUrl: "https://image.lceda.cn/files/lceda-pro-linux-x64-4.1.97.zip", sourceSha256: SOURCE_SHA256,
    sourceBytes: bytes.length, retrievedAt: "2026-11-06", license: "Packaged declaration metadata; signatures only, no implementation",
    ...inventoryApiDeclarations(bytes.toString("utf8")),
  };
  const { namespaces, types, ...provenance } = snapshot;
  const serialized = `${codeLiteral(provenance).slice(0, -1)}, namespaces:[\n${namespaces.map(entry => codeLiteral(entry)).join(",\n")}\n], types:${codeLiteral(types)}}`;
  const output = `// Generated by scripts/generate-packaged-4197-api-catalog.ts from the exact separately pinned declaration.\n// Static candidate discovery only; no installed runtime, CLI, backend or execution admission.\nimport type { ApiDeclarationSnapshot } from "./extension-api-declarations.ts";\n\nexport const packaged4197ApiSnapshot: ApiDeclarationSnapshot = ${serialized};\n`;
  const outputPath = resolve(import.meta.dirname, "../server/src/extension-api-packaged-4197-data.ts");
  if (mode === "--check") {
    if (await readFile(outputPath, "utf8") !== output) { throw new Error("Packaged 4.1.97 declaration catalog is stale."); }
  } else { await writeFile(outputPath, output); }
  process.stdout.write(`Packaged 4.1.97 declaration catalog ${mode === "--check" ? "verified" : "generated"}.\n`);
}

// oxlint-disable-next-line node/no-top-level-await -- A bounded source generator, never an imported facade operation.
await generate();
