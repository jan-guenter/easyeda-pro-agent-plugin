const target = new URL("schematic-wire-budget-regression.cs", import.meta.url);
const source = currentSchematicWireNativeBudgetRegressionSource();
// oxlint-disable-next-line node/no-top-level-await -- Build-only deterministic fixture generation, with no owner or application imports.
