#!/usr/bin/env node
/* oxlint-disable node/no-top-level-await -- ESM-only generator supports direct execution and import by tests. */
import { readFile, writeFile } from "node:fs/promises";
import { builtinModules } from "node:module";
import { dirname, join, relative, resolve } from "node:path";
import { build } from "esbuild";
import { captureContainedRegularFile } from "./bundled-runtime-license.ts";

const ROOT = resolve(import.meta.dirname, "..");
const INPUT_NAMES = ["sqlite-inventory-child.ts", "sqlite-inventory-core.ts", "sqlite-inventory-json.ts"] as const;
// Esbuild's filter uses Go RE2, which does not accept JavaScript's Unicode flag.
// oxlint-disable-next-line require-unicode-regexp
const ALL_PATHS = /.*/;

/** Build only the reviewed builtin-only reader, never a supplied entrypoint. */
export async function generateSqliteInventoryProgram(pluginRoot = ROOT): Promise<string> {
  const sourceRoot = join(pluginRoot, "server", "src");
  const captured = new Map(await Promise.all(INPUT_NAMES.map(async (name) => {
    const path = join(sourceRoot, name);
    return [path, await captureContainedRegularFile(sourceRoot, path, "SQLite reader source")] as const;
  })));
  const builtins = new Set(builtinModules.flatMap((name) => [name, `node:${name}`]));
  const result = await build({
    absWorkingDir: pluginRoot, entryPoints: [join(sourceRoot, INPUT_NAMES[0])],
    bundle: true, platform: "node", format: "esm", target: "node24",
    sourcemap: false, minify: false, legalComments: "none", metafile: true, write: false,
    tsconfigRaw: { compilerOptions: { useDefineForClassFields: true, verbatimModuleSyntax: true } },
    plugins: [{ name: "fixed-sqlite-reader-inputs", setup(api): void {
      api.onResolve({ filter: ALL_PATHS }, (input) => {
        if (builtins.has(input.path)) { return { path: input.path, external: true }; }
        const path = resolve(input.resolveDir, input.path);
        if (!captured.has(path)) { throw new Error("Unreviewed SQLite reader import."); }
        return { path };
      });
      api.onLoad({ filter: ALL_PATHS }, (input) => {
        const value = captured.get(input.path);
        if (value === undefined) { throw new Error("Uncaptured SQLite reader input."); }
        return { contents: value.bytes, loader: "ts", resolveDir: dirname(input.path) };
      });
    } }],
  });
  for (const value of captured.values()) { await value.assertCurrent(); }
  const actual = Object.keys(result.metafile.inputs).map((path) => resolve(pluginRoot, path)).toSorted();
  if (JSON.stringify(actual) !== JSON.stringify([...captured.keys()].toSorted()) || result.outputFiles.length !== 1) {
    throw new Error("SQLite reader compilation closure changed.");
  }
  for (const output of Object.values(result.metafile.outputs)) {
    if (output.imports.some((entry) => entry.external !== true || !builtins.has(entry.path))) {
      throw new Error("SQLite reader has a non-builtin runtime import.");
    }
  }
  const program = result.outputFiles[0]?.text;
  if (program === undefined || Buffer.byteLength(program) > 65_536) { throw new Error("SQLite reader program size refused."); }
  return `// Generated by scripts/generate-sqlite-inventory-program.ts. Do not edit.\n// oxlint-disable-next-line eslint/no-template-curly-in-string -- Embedded source contains its own template literals.\nexport const SQLITE_INVENTORY_PROGRAM = ${JSON.stringify(program)};\n`;
}

async function main(): Promise<void> {
  if (process.argv.length !== 3 || !["--check", "--write"].includes(process.argv[2] ?? "")) {
    throw new Error("Expected --check or --write only.");
  }
  const path = join(ROOT, "server", "src", "sqlite-inventory-program.ts");
  const generated = await generateSqliteInventoryProgram();
  if (process.argv[2] === "--write") { await writeFile(path, generated, { mode: 0o644 }); }
  else if (await readFile(path, "utf8") !== generated) { throw new Error(`Regenerate ${relative(ROOT, path)}.`); }
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === import.meta.filename) {
  try { await main(); }
  catch (error) { process.stderr.write(`${String(error)}\n`); process.exitCode = 1; }
}
