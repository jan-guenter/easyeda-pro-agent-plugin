void test("complete capacity reserves escaped actors, parser rows and cold/cache bounds before Create",async()=>{
 const f=await completeCapacityFixture({username:'Quoted "name"',nickname:"Ω"});
 const result=derive(f.reservation,f.input,f.flow,f.publication);
 requirePrecreate(result,f.reservation,f.input,f.flow,f.publication);
 const copy=requireOriginalCurrentFootprintForwardWriterMainRequestReservationCopy(f.reservation);const cold=deriveCold(result,copy);
 requireCold(cold,result,copy);assert.equal(cold.native.renderer.requestLimit,363);assert.equal(cold.native.renderer.normalClassLimit,328);assert.equal(cold.native.renderer.cleanupClassLimit,35);
 assert.ok(cold.maximumSavedContentBytes>Buffer.byteLength(f.maximum.dataStr)&&cold.maximumSavedContentBytes<=2_097_152);assert.equal(cold.explicitSaveAttempts,0);assert.equal(cold.nativeCreateRequests,0);assert.equal(cold.executionAuthorized,false);
 assert.throws(()=>{requireCold({...cold},result,copy);});assert.throws(()=>{requireCold(cold,{...result},copy);});
 assert.equal(result.bodyLineUpperBound,3);
 assert.equal(result.rawCopyRows,5);
 assert.equal(result.beforeRawRows,4);
 assert.equal(result.closedSuccessorRawRows,10);
 assert.equal(result.startupCallbackUpperBound,2);
 assert.equal(result.callbackRunUpperBound,6);
 assert.equal(result.jointCallbackRunUpperBound,8);
 assert.equal(result.jointControlRequests,34);
 assert.ok(result.maximumActorUtf8Bytes>100);
 assert.ok(result.maximumPlaintextUtf8Bytes>result.maximumBodyUtf8Bytes);
 assert.ok(result.jointComponentManifestBytes<64*1024*1024);
 assert.equal(result.nativeAllocationQualified,false);
 assert.equal(result.wholeWriterReserved,false);
 assert.equal(result.executionAuthorized,false);
 assert.equal(result.saveAuthorized,false);
 const old=f.input.heads[0];assert.ok(old!==undefined);
 const historyUuid="e".repeat(32);
 const plaintext=`{"type":"EDIT_HEAD"}||${JSON.stringify({uuid:"4".repeat(32),username:'Quoted "name"',nickname:"Ω",updateTime:1_700_000_000_005})}|\n${f.maximum.dataStr}`;
 const actual=captureCurrentFootprintSavedFlowCacheInput({...f.input,headHistoryUuid:historyUuid,heads:[{...old,id:37,uuid:historyUuid,parent:old.uuid,key:"f".repeat(32),is_lock:0,created_at:"2026-11-14 10:00:00",updated_at:"2026-11-14 10:00:00"},old],chunks:[...f.input.chunks,{historyUuid,ordinal:0,plaintext,plaintextSha256:sha256Text(plaintext)}]});
 const projection=deriveCurrentFootprintSavedFlowCacheData(actual);
 assert.ok(Buffer.byteLength(projection.headIndex.body)<=result.maximumHeadIndexUtf8Bytes);
 assert.ok(Buffer.byteLength(plaintext)<=result.maximumPlaintextUtf8Bytes);
 assert.equal(requireOriginal(result,f.reservation,f.input,f.flow,f.publication),result);
 assert.throws(()=>requireOriginal({...result},f.reservation,f.input,f.flow,f.publication));
 assert.throws(()=>requireOriginal(new Proxy(result,{}),f.reservation,f.input,f.flow,f.publication));
 assert.throws(()=>requireOriginal(result,{...f.reservation},f.input,f.flow,f.publication));
 assert.throws(()=>derive(f.reservation,f.input,f.flow,{...f.publication}));
});
