import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile } from "node:fs/promises";
import test from "node:test";
import { CURRENT_PCB_209_SELECTION_RELATIONS_FUNCTION } from "../src/current-pcb-209-selection-relations.ts";
import { DIAGNOSTIC_REQUEST_LIMIT, diagnosticExtendedPrimitives209Params, diagnosticNativeRequest, diagnosticSelectionRelations209Params } from "../src/current-pcb-diagnostic-protocol.ts";

const path = String.raw`C:\Reviewed\SelectionRelationsFixture.eprj2`;
const target = { rawWindowsPath: path, projectUuid: createHash("sha256").update(path).digest("hex"),
  documentUuid: "b".repeat(16), expectedSourceSha256: "c".repeat(64), branchUuid: "a".repeat(32) };
function wire(value: unknown): Buffer { return Buffer.from(`${JSON.stringify(value)}\0`); }

void test("209 selection wire reconstructs only the fixed original command and exact ordered component IDs", () => {
  const componentIds = ["component-2", 'quote"slash\\\n', "component-1"];
  const command = { id: 103, method: "Runtime.callFunctionOn", params: diagnosticSelectionRelations209Params("ui-original", target, componentIds), sessionId: "session-original" };
  assert.deepEqual(diagnosticNativeRequest(wire(command)), { action: "send", requestId: 103, method: "Runtime.callFunctionOn",
    sessionId: "session-original", uniqueContextId: "ui-original", pcbSelectionRelations209Phase: "observe", componentIds, targetRawWindowsPath: path,
    targetProjectUuid: target.projectUuid, targetBranchUuid: target.branchUuid, targetDocumentUuid: target.documentUuid,
    targetExpectedSourceSha256: target.expectedSourceSha256 });
  assert.equal(DIAGNOSTIC_REQUEST_LIMIT, 103);
  assert.throws(() => diagnosticNativeRequest(wire({ ...command, id: 104 })));
  for (const params of [{ ...command.params, functionDeclaration: "async()=>1" }, { ...command.params, throwOnSideEffect: true },
    { ...command.params, arguments: [{ value: target }, { value: "open-document" }, { value: [] }] },
    { ...command.params, arguments: [{ value: target }, { value: "observe" }] },
    { ...command.params, arguments: [{ value: { ...target, branchUuid: undefined } }, { value: "observe" }, { value: [] }] },
    { ...command.params, uniqueContextId: "" }, { ...command.params, code: "arbitrary" }, { ...command.params, userGesture: true }]) {
    assert.throws(() => diagnosticNativeRequest(wire({ ...command, params })));
  }
  for (const invalidIds of [null, "one", ["one", "one"], [""], [null], [7], ["x".repeat(257)], ["\uD800"], Array.from({ length: 17 }, (_, index) => `c${index}`)]) {
    assert.throws(() => diagnosticNativeRequest(wire({ ...command, params: { ...command.params,
      arguments: [{ value: target }, { value: "observe" }, { value: invalidIds }] } })));
  }
  const older = diagnosticExtendedPrimitives209Params("ui-original", target);
  assert.throws(() => diagnosticNativeRequest(wire({ ...command, params: { ...older, arguments: [...older.arguments, { value: [] }] } })));
  const empty = diagnosticSelectionRelations209Params("ui-original", target, []);
  assert.deepEqual(diagnosticNativeRequest(wire({ ...command, params: empty }))["componentIds"], []);
});

