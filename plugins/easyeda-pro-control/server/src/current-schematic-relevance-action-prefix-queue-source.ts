export function qualifyCurrentSchematicRelevancePrefixQueueSource(source:string):0|1{if(!source.isWellFormed()){throw new Error("RELEVANCE_PREFIX_QUEUE_SOURCE");}for(const variant of [0,1] as const){const profile=CURRENT_SCHEMATIC_RELEVANCE_PREFIX_QUEUE_SOURCE[variant];if(Buffer.byteLength(source)===profile.bytes&&digest(source)===profile.sha256){for(const role of CURRENT_SCHEMATIC_RELEVANCE_PREFIX_QUEUE_ROLES){const row=profile.roles[role],text=source.slice(row.start,row.end);if(Buffer.byteLength(text)!==row.bytes||digest(text)!==row.sha256){throw new Error("RELEVANCE_PREFIX_QUEUE_SPAN");}}return variant;}}throw new Error("RELEVANCE_PREFIX_QUEUE_SOURCE");}
