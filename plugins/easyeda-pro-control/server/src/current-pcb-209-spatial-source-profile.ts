/** Full fixed asset first, then every fixed UTF-16 slice. No supplied offsets,
 * source evaluation, application reads or native dispatch. */
function hash(value: string): string { return createHash("sha256").update(value).digest("hex"); }
export function inspectCurrentPcb209SpatialSource(input: unknown): Readonly<{
  sourceProfileMatches: boolean; compatibilityAdmitted: false; executionAuthorized: false;
}> {
  if (typeof input !== "string" || !input.isWellFormed() || input.length > 12 * 1024 * 1024) {
    throw new Error("PCB209_SPATIAL_SOURCE_INPUT");
  }
  const profile = CURRENT_PCB_209_SPATIAL_SOURCE_PROFILE;
  const sourceProfileMatches = Buffer.byteLength(input) === profile.bytes && hash(input) === profile.sha256 &&
    Object.values(profile.spans).every(span => {
      const value = input.slice(span.start, span.end);
      return Buffer.byteLength(value) === span.bytes && hash(value) === span.sha256;
    }) && CURRENT_PCB_209_SPATIAL_FUNCTION_PROFILES.every(fn => {
      const value = input.slice(fn.sourceStart, fn.sourceEnd);
      return Buffer.byteLength(value) === fn.sourceBytes && hash(value) === fn.sourceSha256;
    });
  return Object.freeze({ sourceProfileMatches, compatibilityAdmitted: false, executionAuthorized: false });
}
